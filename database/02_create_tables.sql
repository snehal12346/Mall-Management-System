-- Drop tables if already exist in reverse dependency order
DROP TABLE IF EXISTS OFFER_USAGE CASCADE;
DROP TABLE IF EXISTS OFFER CASCADE;
DROP TABLE IF EXISTS MAINTENANCE_ASSIGNMENT CASCADE;
DROP TABLE IF EXISTS MAINTENANCE_REQUEST CASCADE;
DROP TABLE IF EXISTS COMPLAINT_ASSIGNMENT CASCADE;
DROP TABLE IF EXISTS COMPLAINT CASCADE;
DROP TABLE IF EXISTS EMPLOYEE CASCADE;
DROP TABLE IF EXISTS EVENT_REGISTRATION CASCADE;
DROP TABLE IF EXISTS EVENT CASCADE;
DROP TABLE IF EXISTS PARKING_ENTRY CASCADE;
DROP TABLE IF EXISTS PARKING_SLOT CASCADE;
DROP TABLE IF EXISTS VEHICLE CASCADE;
DROP TABLE IF EXISTS PAYMENT CASCADE;
DROP TABLE IF EXISTS PURCHASE_DETAIL CASCADE;
DROP TABLE IF EXISTS PURCHASE CASCADE;
DROP TABLE IF EXISTS PRODUCT CASCADE;
DROP TABLE IF EXISTS LEASE CASCADE;
DROP TABLE IF EXISTS TENANT CASCADE;
DROP TABLE IF EXISTS SHOP CASCADE;
DROP TABLE IF EXISTS MEMBERSHIP CASCADE;
DROP TABLE IF EXISTS CUSTOMER CASCADE;
DROP TABLE IF EXISTS APP_USER CASCADE;

-- ----------------------------------------------------------------------------
-- 1. CUSTOMER TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE CUSTOMER (
    customer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    phone VARCHAR(20),
    email VARCHAR(100),
    registration_date DATE DEFAULT CURRENT_DATE
);

-- ----------------------------------------------------------------------------
-- 2. MEMBERSHIP TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE MEMBERSHIP (
    membership_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INT UNIQUE NOT NULL,
    membership_type VARCHAR(50) NOT NULL,
    join_date DATE DEFAULT CURRENT_DATE,
    points INT DEFAULT 0,
    status VARCHAR(20) DEFAULT 'Active'
);

-- ----------------------------------------------------------------------------
-- 3. SHOP TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE SHOP (
    shop_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_name VARCHAR(100) NOT NULL,
    category VARCHAR(50),
    floor VARCHAR(30),
    contact_no VARCHAR(20)
);

-- ----------------------------------------------------------------------------
-- 4. TENANT TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE TENANT (
    tenant_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_name VARCHAR(100) NOT NULL,
    contact_no VARCHAR(20),
    email VARCHAR(100)
);

-- ----------------------------------------------------------------------------
-- 5. LEASE TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE LEASE (
    lease_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INT NOT NULL,
    tenant_id INT NOT NULL,
    lease_start DATE NOT NULL,
    lease_end DATE NOT NULL,
    monthly_rent DECIMAL(12,2) NOT NULL,
    lease_status VARCHAR(20) DEFAULT 'Active'
);

-- ----------------------------------------------------------------------------
-- 6. PRODUCT TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE PRODUCT (
    product_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INT NOT NULL,
    product_name VARCHAR(100) NOT NULL,
    category VARCHAR(50),
    price DECIMAL(10,2) NOT NULL,
    stock_quantity INT DEFAULT 0
);

-- ----------------------------------------------------------------------------
-- 7. PURCHASE TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE PURCHASE (
    purchase_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INT NOT NULL,
    shop_id INT NOT NULL,
    purchase_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    total_amount DECIMAL(12,2) DEFAULT 0.00
);

-- ----------------------------------------------------------------------------
-- 8. PURCHASE_DETAIL TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE PURCHASE_DETAIL (
    purchase_detail_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id INT NOT NULL,
    product_id INT NOT NULL,
    quantity INT NOT NULL,
    unit_price DECIMAL(10,2) NOT NULL,
    discount DECIMAL(10,2) DEFAULT 0.00
);

-- ----------------------------------------------------------------------------
-- 9. PAYMENT TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE PAYMENT (
    payment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id INT NOT NULL,
    payment_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    amount DECIMAL(12,2) NOT NULL,
    payment_method VARCHAR(30) NOT NULL,
    payment_status VARCHAR(20) DEFAULT 'Completed'
);

-- ----------------------------------------------------------------------------
-- 10. VEHICLE TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE VEHICLE (
    vehicle_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INT,
    vehicle_number VARCHAR(20) UNIQUE NOT NULL,
    vehicle_type VARCHAR(30) NOT NULL
);

-- ----------------------------------------------------------------------------
-- 11. PARKING_SLOT TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE PARKING_SLOT (
    slot_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    floor VARCHAR(30) NOT NULL,
    slot_number VARCHAR(20) NOT NULL,
    vehicle_type VARCHAR(30) NOT NULL,
    status VARCHAR(20) DEFAULT 'Available'
);

-- ----------------------------------------------------------------------------
-- 12. PARKING_ENTRY TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE PARKING_ENTRY (
    entry_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id INT NOT NULL,
    slot_id INT NOT NULL,
    entry_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    exit_time TIMESTAMP,
    parking_fee DECIMAL(10,2) DEFAULT 0.00
);

-- ----------------------------------------------------------------------------
-- 13. EVENT TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE EVENT (
    event_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name VARCHAR(150) NOT NULL,
    event_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    location VARCHAR(100) NOT NULL,
    capacity INT NOT NULL
);

-- ----------------------------------------------------------------------------
-- 14. EVENT_REGISTRATION TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE EVENT_REGISTRATION (
    registration_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id INT NOT NULL,
    customer_id INT NOT NULL,
    registration_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    attendance_status VARCHAR(20) DEFAULT 'Registered',
    CONSTRAINT uq_event_customer UNIQUE (event_id, customer_id)
);

-- ----------------------------------------------------------------------------
-- 15. EMPLOYEE TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE EMPLOYEE (
    employee_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_name VARCHAR(100) NOT NULL,
    department VARCHAR(50) NOT NULL,
    designation VARCHAR(50) NOT NULL,
    phone VARCHAR(20) NOT NULL
);

-- ----------------------------------------------------------------------------
-- 16. COMPLAINT TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE COMPLAINT (
    complaint_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INT NOT NULL,
    complaint_type VARCHAR(50) NOT NULL,
    description VARCHAR(500),
    complaint_date DATE DEFAULT CURRENT_DATE,
    status VARCHAR(30) DEFAULT 'Open',
    priority VARCHAR(20) DEFAULT 'Medium',
    resolution_date DATE
);

-- ----------------------------------------------------------------------------
-- 17. COMPLAINT_ASSIGNMENT TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE COMPLAINT_ASSIGNMENT (
    assignment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id INT NOT NULL,
    employee_id INT NOT NULL,
    assigned_date DATE DEFAULT CURRENT_DATE,
    assignment_status VARCHAR(30) DEFAULT 'Assigned'
);

-- ----------------------------------------------------------------------------
-- 18. MAINTENANCE_REQUEST TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE MAINTENANCE_REQUEST (
    request_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reported_by_customer_id INT,
    issue_type VARCHAR(50) NOT NULL,
    description VARCHAR(500),
    request_date DATE DEFAULT CURRENT_DATE,
    status VARCHAR(30) DEFAULT 'Pending',
    completion_date DATE
);

-- ----------------------------------------------------------------------------
-- 19. MAINTENANCE_ASSIGNMENT TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE MAINTENANCE_ASSIGNMENT (
    assignment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id INT NOT NULL,
    employee_id INT NOT NULL,
    assigned_date DATE DEFAULT CURRENT_DATE,
    assignment_status VARCHAR(30) DEFAULT 'Assigned'
);

-- ----------------------------------------------------------------------------
-- 20. OFFER TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE OFFER (
    offer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INT NOT NULL,
    offer_name VARCHAR(150) NOT NULL,
    discount_percentage DECIMAL(5,2) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL
);

-- ----------------------------------------------------------------------------
-- 21. OFFER_USAGE TABLE
-- ----------------------------------------------------------------------------
CREATE TABLE OFFER_USAGE (
    usage_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id INT NOT NULL,
    customer_id INT NOT NULL,
    purchase_id INT NOT NULL,
    used_date DATE DEFAULT CURRENT_DATE
);

-- ----------------------------------------------------------------------------
-- 22. APP_USER TABLE (Authentication & Authorization)
-- ----------------------------------------------------------------------------
CREATE TABLE APP_USER (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    role VARCHAR(30) DEFAULT 'Staff',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    is_active BOOLEAN DEFAULT TRUE
);
